// Every country an admin/reception staff can pick as a patient's Nationality (and its
// phone dialing code, reused for the phone-code selector on the same form) - all UN
// member states plus a handful of commonly listed territories (Hong Kong, Macau, Taiwan,
// Kosovo, Vatican City, Palestine). This is fixed, universal reference data (ISO
// 3166/ITU-T E.164 standards), not something a hospital admin curates per-tenant, so it's
// a static list here rather than a per-company DB catalog.
